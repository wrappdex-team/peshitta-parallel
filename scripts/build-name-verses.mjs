// Precompute /names verse lists with the reader's nameRuns matcher.
// Writes src/lib/name-verse-pack.ts. Does not edit names.json or scripture.
import { writeFileSync } from "node:fs";
import { buildNameVersePack } from "../src/lib/name-verse-build.ts";

const pack = buildNameVersePack();
const out = `// Generated by scripts/build-name-verses.mjs. Lists are keyed by card id.
// Regenerate after a names or verse-text change: node scripts/build-name-verses.mjs
export const NAME_VERSE_PACK = ${JSON.stringify(pack)};
`;
writeFileSync(new URL("../src/lib/name-verse-pack.ts", import.meta.url), out);
console.log(`name verse pack base64 ${pack.length}`);
