// Precompute /names verse lists with the reader's nameRuns matcher.
// Writes src/lib/name-verse-pack.ts. Does not edit names.json or scripture.
import { readFileSync, writeFileSync } from "node:fs";
import { BOOKS } from "../src/data/edition.ts";
import { NAMES, nameRuns } from "../src/lib/names.ts";

const byId = new Map(NAMES.map((row) => [row.id, []]));
let ordinal = 0;
for (const book of BOOKS) {
  const data = JSON.parse(readFileSync(new URL(`../src/data/nt/${book.id}.json`, import.meta.url), "utf8"));
  data.chapters.forEach((chapter) => {
    for (const verse of chapter) {
      const seen = new Set();
      for (const run of nameRuns(verse.en || "")) {
        if (run.kind === "name") seen.add(run.id);
      }
      for (const id of seen) byId.get(id)?.push(ordinal);
      ordinal += 1;
    }
  });
}

const bytes = [];
function pushVar(value) {
  let rest = value;
  while (rest > 127) {
    bytes.push((rest & 127) | 128);
    rest >>= 7;
  }
  bytes.push(rest);
}

for (const row of NAMES) {
  const list = byId.get(row.id) ?? [];
  const have = row.refs?.length || 1;
  if (list.length <= have) {
    bytes.push(0, 0);
    continue;
  }
  const start = bytes.length;
  bytes.push(0, 0);
  let prev = -1;
  for (const at of list) {
    pushVar(at - prev);
    prev = at;
  }
  const length = bytes.length - start - 2;
  bytes[start] = length & 255;
  bytes[start + 1] = (length >> 8) & 255;
}

const pack = Buffer.from(bytes).toString("base64");
const out = `// Generated by scripts/build-name-verses.mjs. Verse lists for cards whose nameRuns hits outrun refs.
export const NAME_VERSE_PACK = ${JSON.stringify(pack)};
`;
writeFileSync(new URL("../src/lib/name-verse-pack.ts", import.meta.url), out);
console.log(`name verse pack ${bytes.length} bytes, base64 ${pack.length}, verses walked ${ordinal}`);
